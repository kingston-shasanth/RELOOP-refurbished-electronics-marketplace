const expandCatalogue = async () => {
  try {
    console.log('[RELOOP Catalogue Expansion] Connecting to MongoDB...');
    await connectDB();

    console.log(`[RELOOP Catalogue Expansion] Processing ${catalogueData.length} certified products across all 8 categories...`);
    let createdCount = 0;
    let updatedCount = 0;

    for (const item of catalogueData) {
      let product = await Product.findOne({ slug: item.slug });

      if (product) {
        // Idempotent update of catalogue metadata and local images
        product.title = item.title;
        product.brand = item.brand;
        product.category = item.category;
        product.subcategory = item.subcategory;
        product.refurbishedPrice = item.refurbishedPrice;
        product.originalRetailPrice = item.originalRetailPrice;
        product.stockCount = item.stockCount;
        product.conditionGrade = item.conditionGrade;
        product.conditionSummary = item.conditionSummary;
        product.primaryImage = item.primaryImage;
        product.images = item.images;
        product.warrantyMonths = item.warrantyMonths;
        product.isFeatured = item.isFeatured;
        product.specifications = item.specifications;
        await product.save();
        updatedCount++;
      } else {
        // Create new certified product entry
        product = await Product.create(item);
        createdCount++;
      }

      // Check or create Digital Product Passport
      let passport = await DigitalPassport.findOne({ productId: product._id });
      const hasBattery = item.specifications.batteryHealthPercent !== null;

      const passportPayload = {
        productId: product._id,
        deviceSerialNumber: `RLP-${product.slug.substring(0, 8).toUpperCase()}-2026`,
        diagnosticSummaryScore: product.conditionGrade === 'Pristine' ? 98 : product.conditionGrade === 'Excellent' ? 94 : 90,
        subsystemChecks: {
          screen: {
            status: 'Pass',
            notes: 'Color uniformity, backlight integrity, and touch response certified within OEM limits.',
          },
          battery: {
            status: hasBattery ? 'Pass' : 'Not Applicable',
            healthPercent: hasBattery ? item.specifications.batteryHealthPercent : null,
            cycleCount: hasBattery ? 85 : null,
          },
          chassis: {
            status: product.conditionGrade === 'Pristine' ? 'Flawless' : 'Micro-scratches',
            notes: product.conditionSummary,
          },
          portsAndCharging: {
            status: 'Pass',
            notes: 'All I/O connectors, USB power delivery and contacts ultrasonic-cleaned and impedance-tested.',
          },
          camerasAndSensors: {
            status: 'Pass',
            notes: 'Sensors, gyroscopes, biometric scanners and optics calibrated against laboratory baseline.',
          },
          audioAndMics: {
            status: 'Pass',
            notes: 'Acoustic frequency response and stereo balance verified.',
          },
          connectivityWifiBt: {
            status: 'Pass',
            notes: 'Wi-Fi 6 and Bluetooth 5.x throughput tested under sustained packet transfer.',
          },
        },
        oemPartsReplaced: [],
        environmentalImpact: {
          eWastePreventedGrams: item.category === 'Laptops' ? 1800 : item.category === 'Smartphones' ? 185 : 450,
          carbonFootprintSavedKg: item.category === 'Laptops' ? 190 : item.category === 'Smartphones' ? 62 : 45,
        },
      };

      if (!passport) {
        passport = await DigitalPassport.create(passportPayload);
      } else {
        passport.diagnosticSummaryScore = passportPayload.diagnosticSummaryScore;
        passport.subsystemChecks = passportPayload.subsystemChecks;
        passport.environmentalImpact = passportPayload.environmentalImpact;
        await passport.save();
      }

      // Associate passport back to product
      if (!product.digitalPassportId || product.digitalPassportId.toString() !== passport._id.toString()) {
        product.digitalPassportId = passport._id;
        await product.save();
      }
    }

    const totalProducts = await Product.countDocuments();
    const categoriesCount = await Product.distinct('category');

    console.log('------------------------------------------------------------');
    console.log(`[RELOOP Catalogue Expansion Completed Successfully]`);
    console.log(`Created: ${createdCount} products`);
    console.log(`Updated: ${updatedCount} products`);
    console.log(`Total Active Products in Database: ${totalProducts}`);
    console.log(`Populated Categories (${categoriesCount.length}/8):`, categoriesCount);
    console.log('------------------------------------------------------------');

    process.exit(0);
  } catch (error) {
    console.error('[RELOOP Catalogue Expansion ERROR]:', error);
    process.exit(1);
  }
};

expandCatalogue();
